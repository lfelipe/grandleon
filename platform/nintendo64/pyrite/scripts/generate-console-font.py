"""Pack pinned Spleen Latin-1 glyphs into TMEM-sized N64 IA4 banks."""
from pathlib import Path
import argparse


def generate(repo: Path) -> str:
    lines = (repo / 'assets/fonts/spleen/spleen-6x12.bdf').read_text().splitlines()
    ascent = int(next(line.split()[1] for line in lines if line.startswith('FONT_ASCENT ')))
    glyphs = {}
    index = 0
    while index < len(lines):
        if not lines[index].startswith('STARTCHAR '):
            index += 1
            continue
        end = lines.index('ENDCHAR', index)
        record = lines[index:end]
        code = int(next(line.split()[1] for line in record if line.startswith('ENCODING ')))
        if 32 <= code <= 255:
            width, height, left, bottom = map(int, next(line for line in record if line.startswith('BBX ')).split()[1:])
            pixels = [0] * (8 * 12)
            top = ascent - bottom - height
            bitmap = record.index('BITMAP') + 1
            for row, value in enumerate(record[bitmap:bitmap + height]):
                bits = int(value, 16)
                for column in range(width):
                    if bits & (1 << (((width + 7) // 8 * 8) - 1 - column)):
                        x, y = left + column, top + row
                        assert 0 <= x < 6 and 0 <= y < 12
                        pixels[y * 8 + x] = 15
            glyphs[code] = pixels
        index = end + 1
    assert set(range(160, 256)) <= glyphs.keys()
    atlas = []
    for bank in range(14):
        pixels = []
        for y in range(12):
            for column in range(16):
                code = 32 + bank * 16 + column
                glyph = glyphs.get(code, glyphs[ord('?')])
                pixels.extend(glyph[y * 8:y * 8 + 8])
        atlas.append([pixels[i] << 4 | pixels[i + 1] for i in range(0, len(pixels), 2)])
    output = ['// Generated by scripts/generate-console-font.py; do not edit.',
              '// Spleen 2.2.0, Copyright Frederic Cambus, BSD-2-Clause.',
              '// License: assets/fonts/spleen/LICENSE.', '#pragma once', '#include <cstdint>',
              'namespace grandleon::nintendo64::pyrite::console_font {',
              'inline constexpr unsigned first = 32, advance = 6, height = 12;',
              'inline constexpr unsigned bank_width = 128, bank_bytes = 768;',
              'alignas(8) inline constexpr std::uint8_t banks[14][bank_bytes] = {']
    for bank in atlas:
        output.append('    {')
        for offset in range(0, len(bank), 24):
            output.append('        ' + ','.join(f'0x{value:02x}' for value in bank[offset:offset + 24]) + ',')
        output.append('    },')
    output.extend(['};', '}'])
    return '\n'.join(output) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--repo', type=Path, default=Path(__file__).resolve().parents[4])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / 'project/src/user/ConsoleFont.hpp'
    generated = generate(args.repo)
    if args.check:
        assert target.read_text() == generated, 'N64 console font needs regeneration'
    else:
        target.write_text(generated)


if __name__ == '__main__':
    main()
