// One row of one glyph: the top five bits are the five pixels, left to right.
// Out of range in either argument is blank, so a caller walking a fixed
// rectangle never reads past the table.
[[nodiscard]] constexpr std::uint8_t glyph_row(int character, int row) noexcept {
    if (row < 0 || row >= glyph_rows) return 0;
    const int index = character - first_glyph;
    if (index < 0 || index >= glyph_count) return 0;
    return detail::glyphs[index][row];
}

// Whether one pixel of one glyph is ink. `x` counts from the left of the
// eight-pixel cell, so the three rightmost columns are the tracking and are
// always clear.
[[nodiscard]] constexpr bool glyph_pixel(int character, int x, int row) noexcept {
    if (x < 0 || x >= glyph_width) return false;
    return (glyph_row(character, row) & (0x80U >> (x + 1))) != 0;
}

