import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compileFromFile } from "json-schema-to-typescript";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const editorDirectory = path.resolve(scriptDirectory, "..");
const repositoryRoot = path.resolve(editorDirectory, "..");
const schemaDirectory = path.join(repositoryRoot, "schemas/source/v1");
const schemaPath = path.join(schemaDirectory, "project.schema.json");
const outputPath = path.join(
  editorDirectory,
  "src/generated/source-v1.ts"
);
const schemaOutputPath = path.join(
  editorDirectory,
  "src/generated/source-v1-schemas.ts"
);
const validatorOutputPath = path.join(
  editorDirectory,
  "src/generated/source-v1-validator.ts"
);
const check = process.argv.includes("--check");

const bannerComment = `/*
 * Generated from schemas/source/v1/project.schema.json.
 * Do not edit this file; run npm run generate:source-types.
 */
`;

const publicNames = new Map([
  ["project.schema.json", "SourceProject"],
  ["class.schema.json", "SourceClass"],
  ["weapon-type.schema.json", "SourceWeaponType"],
  ["item-type.schema.json", "SourceItemType"],
  ["unit-type.schema.json", "SourceUnitType"],
  ["weapon.schema.json", "SourceWeapon"],
  ["item.schema.json", "SourceItem"],
  ["map.schema.json", "SourceMap"],
  ["faction.schema.json", "SourceFaction"],
  ["ability.schema.json", "SourceAbility"],
  ["objective.schema.json", "SourceObjective"],
  ["campaign.schema.json", "SourceCampaign"],
  ["dialogue.schema.json", "SourceDialogue"]
]);

const generated = await compileFromFile(schemaPath, {
  bannerComment,
  cwd: schemaDirectory,
  customName(schema, inferredName) {
    const id = typeof schema.$id === "string" ? schema.$id : "";
    const filename = id.slice(id.lastIndexOf("/") + 1);
    return publicNames.get(filename) ?? inferredName;
  },
  unknownAny: true,
  style: {
    bracketSpacing: true,
    printWidth: 100,
    semi: true,
    singleQuote: false,
    tabWidth: 2,
    trailingComma: "none",
    useTabs: false
  }
});

const schemaFilenames = (await fs.readdir(schemaDirectory))
  .filter((filename) => filename.endsWith(".schema.json"))
  .sort();
const schemas = await Promise.all(
  schemaFilenames.map(async (filename) =>
    JSON.parse(await fs.readFile(path.join(schemaDirectory, filename), "utf8"))
  )
);
const generatedSchemas = `${bannerComment}
export const sourceV1Schemas: readonly object[] = ${JSON.stringify(
  schemas,
  null,
  2
)} as const;
`;
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { source: true, esm: true }
});
for (const schema of schemas) ajv.addSchema(schema);
const projectValidator = ajv.getSchema(
  "https://grandleon.dev/schemas/source/v1/project.schema.json"
);
if (!projectValidator) throw new Error("source project schema was not registered");
const standaloneValidator = standaloneCode(ajv, projectValidator)
  .replace(
    /const (func\d+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
    "const $1 = ucs2length;"
  )
  .replace(
    /const (func\d+) = require\("ajv\/dist\/runtime\/equal"\)\.default;/g,
    "const $1 = equal;"
  );
if (standaloneValidator.includes("require(")) {
  throw new Error("generated browser validator contains CommonJS runtime imports");
}
const generatedValidator = `${bannerComment}
// @ts-nocheck -- generated by Ajv; checked through its typed import boundary.
const ucs2length = (value) => Array.from(value).length;
function equal(left, right) {
  if (left === right) return true;
  if (Array.isArray(left)) {
    return Array.isArray(right) &&
      left.length === right.length &&
      left.every((value, index) => equal(value, right[index]));
  }
  if (left && right && typeof left === "object" && typeof right === "object") {
    const keys = Object.keys(left);
    return keys.length === Object.keys(right).length &&
      keys.every((key) =>
        Object.prototype.hasOwnProperty.call(right, key) &&
        equal(left[key], right[key])
      );
  }
  return false;
}
${standaloneValidator}
`;

if (check) {
  const outputs = [
    [outputPath, generated],
    [schemaOutputPath, generatedSchemas],
    [validatorOutputPath, generatedValidator]
  ];
  for (const [filename, expected] of outputs) {
    let existing;
    try {
      existing = await fs.readFile(filename, "utf8");
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }
    if (existing !== expected) {
      console.error(
        "generated source contracts are stale; run npm run --prefix editor generate:source-types"
      );
      process.exitCode = 1;
    }
  }
} else {
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, generated, "utf8");
  await fs.writeFile(schemaOutputPath, generatedSchemas, "utf8");
  await fs.writeFile(validatorOutputPath, generatedValidator, "utf8");
}
