// Packs the compiled WebAssembly simulation module into a checked-in
// TypeScript module.
//
// The module is embedded as base64 rather than shipped as a separate asset so
// that it loads identically in the browser, in Vitest under Node, from a
// non-root deployment sub-path, and offline. There is no fetch, no asset URL to
// resolve, and no MIME configuration to get wrong.
//
//   node scripts/generate-wasm-module.mjs <path-to.wasm>
//   node scripts/generate-wasm-module.mjs <path-to.wasm> --check
//
// It is normally invoked through platform/web/scripts/build-wasm.sh, which
// produces the input inside the pinned Emscripten SDK container.

import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const editorDirectory = path.resolve(scriptDirectory, "..");
const outputPath = path.join(
  editorDirectory,
  "src/generated/simulation-module.ts"
);

const args = process.argv.slice(2);
const check = args.includes("--check");
const inputPath = args.find((argument) => !argument.startsWith("--"));
if (!inputPath) {
  console.error("usage: generate-wasm-module.mjs <path-to.wasm> [--check]");
  process.exit(2);
}

const wasm = await fs.readFile(inputPath);
if (wasm.subarray(0, 4).toString("latin1") !== "\0asm") {
  console.error(`${inputPath} is not a WebAssembly module`);
  process.exit(1);
}

const digest = crypto.createHash("sha256").update(wasm).digest("hex");
const base64 = wasm.toString("base64");
// Wrapped so that a rebuild produces a readable diff rather than one enormous
// line that no review tool will render.
const chunks = base64.match(/.{1,96}/gu) ?? [];

const generated = `/*
 * Generated from platform/web/src/simulation_abi.cpp and the engine libraries
 * it links, compiled by the pinned Emscripten SDK container.
 *
 * It carries the parts of the LLVM runtime Emscripten links in (libc++,
 * libc++abi and compiler-rt) under the Apache License 2.0 with the LLVM
 * exception. See NOTICE.
 *
 * Do not edit this file. Rebuild it with:
 *   cmake --build build --target grandleon_wasm
 *
 * Verify it with:
 *   cmake --build build --target grandleon_wasm_check
 *
 * bytes:  ${wasm.length}
 * sha256: ${digest}
 */

/** SHA-256 of the module bytes, for build provenance and drift diagnostics. */
export const simulationModuleDigest =
  "${digest}";

/** Size of the decoded module in bytes. */
export const simulationModuleByteLength = ${wasm.length};

const encoded = [
${chunks.map((chunk) => `  "${chunk}"`).join(",\n")}
].join("");

/** Decoded WebAssembly bytes for the authoritative simulation. */
export function simulationModuleBytes(): Uint8Array {
  const binary =
    typeof atob === "function"
      ? atob(encoded)
      : Buffer.from(encoded, "base64").toString("latin1");
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index += 1) {
    bytes[index] = binary.charCodeAt(index);
  }
  return bytes;
}
`;

if (check) {
  let existing;
  try {
    existing = await fs.readFile(outputPath, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (existing !== generated) {
    console.error(
      "the checked-in WebAssembly module is stale; " +
        "rebuild it with cmake --build build --target grandleon_wasm"
    );
    process.exitCode = 1;
  }
} else {
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, generated, "utf8");
  console.log(
    `wrote ${path.relative(editorDirectory, outputPath)} ` +
      `(${wasm.length} bytes, sha256 ${digest.slice(0, 16)}…)`
  );
}
